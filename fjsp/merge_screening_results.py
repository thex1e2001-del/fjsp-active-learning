"""Validate and merge the frozen five-seed experiment; generate paper tables.

Run from any directory: python fjsp/merge_screening_results.py
Original result files are preserved. No solver is run by this script.
"""
import json
from pathlib import Path

from summarize_calibrated import summarize

ROOT = Path(__file__).resolve().parent
SOURCES = ["calibrated_screening_formal_small.json", "calibrated_screening_seeds45_46.json"]


def main():
    rows = []
    for name in SOURCES:
        rows.extend(json.loads((ROOT / "results" / name).read_text(encoding="utf-8")))
    expected = {(f"mk{i:02d}", s) for i in range(1, 11) for s in range(42, 47)}
    if len(rows) != 50 or {(r["instance"], r["seed"]) for r in rows} != expected:
        raise ValueError("Expected exactly 10 instances x 5 unique seeds")
    same_set = same_best = both_feasible = fallback = 0
    for row in rows:
        meta = row["calibration"]
        settings = (meta["n_train"], meta["n_test"], meta["calibration_requested"], row["top_k"], row["verify_time"])
        if settings != (300, 150, 15, 5, 1.0):
            raise ValueError(f"Protocol mismatch: {settings}")
        scorers = {s["scorer"]: s for s in row["scorers"]}
        if set(scorers) != {"LB", "RF-H", "CRF", "HeurSeq", "Random"}:
            raise ValueError("Missing or unexpected scorers")
        for scorer in scorers.values():
            selected = scorer["selected"]
            if len(selected) != 5 or len({x["assignment_id"] for x in selected}) != 5:
                raise ValueError("Invalid Top-5 selection")
            feasible = [x["makespan"] for x in selected if x["has_solution"]]
            if scorer["best_selected_makespan"] != min(feasible, default=None):
                raise ValueError("Best makespan inconsistent with candidate records")
        a, b = scorers["CRF"], scorers["RF-H"]
        same_set += {x["assignment_id"] for x in a["selected"]} == {x["assignment_id"] for x in b["selected"]}
        if a["best_selected_makespan"] is not None and b["best_selected_makespan"] is not None:
            both_feasible += 1
            same_best += abs(a["best_selected_makespan"] - b["best_selected_makespan"]) <= 1e-3
        fallback += meta["crf_fallback"] is not None
    rows.sort(key=lambda r: (r["instance"], r["seed"]))
    output = ROOT / "results" / "calibrated_screening_five_seeds.json"
    output.write_text(json.dumps(rows, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    audit = dict(sources=SOURCES, runs=len(rows), crf_fallback=fallback,
                 identical_crf_rf_h_candidate_sets=same_set,
                 both_feasible_runs=both_feasible, tied_best_makespans=same_best,
                 tie_tolerance=1e-3)
    (ROOT / "results" / "calibrated_screening_five_seeds.audit.json").write_text(
        json.dumps(audit, indent=2) + "\n", encoding="utf-8")
    summary = summarize(rows)
    methods = ["LB", "RF-H", "CRF", "HeurSeq", "Random"]
    table = [r"% Generated by merge_screening_results.py; do not hand-edit.",
             r"\begin{table}[htbp]\centering\small",
             r"\caption{Five-seed extension: mean best feasible incumbent (successful runs/5). Means conditional on success are not directly comparable when counts differ.}\label{tab:five-seeds}",
             r"\begin{tabular}{lrrrrr}\toprule",
             "Instance & " + " & ".join(methods) + r" \\ \midrule"]
    lookup = {(s["instance"], s["scorer"]): s for s in summary}
    for inst in sorted({r["instance"] for r in rows}):
        cells = []
        for method in methods:
            s = lookup[inst, method]
            value = s["mean_best_makespan"]
            cells.append("-- (0/5)" if value is None else f"{value:.1f} ({s['seeds']}/5)")
        table.append(inst + " & " + " & ".join(cells) + r" \\")
    table += [r"\bottomrule\end{tabular}\end{table}", ""]
    (ROOT / "paper" / "five_seed_tables.tex").write_text("\n".join(table), encoding="utf-8")
    print(json.dumps(audit, indent=2))


if __name__ == "__main__":
    main()
